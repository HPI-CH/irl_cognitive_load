def convert_unix_time(unix_time: str) -> datetime.datetime:
        """
        
        Convert the unix-time to a human-readable time

        Parameters
        ----------
        unix_time: str
            Time from the recording

        Returns
        -------
        datetime: datetime.datetime 
            human-readable time
        
        """
        return datetime.datetime.fromtimestamp(unix_time, tz=datetime.timezone.utc).astimezone(pytz.timezone('US/Pacific'))
    



def set_time_(freq: int, start_time: float, len_frame: int) -> list[datetime.datetime]:
    """
    Generates a list of datetime objects based on the given frequency and start time.

    Parameters
    ----------
    freq : int
        Sampling frequency in Hertz (Hz).
    start_time : float
        Unix start time in seconds.
    len_frame : int
        Length of the time frame (number of samples).

    Returns
    -------
    list of datetime.datetime
        List of datetime objects representing the time points.

    Notes
    -----
    - The function `convert_unix_time` is used to convert the Unix start time to a datetime object.
    - The time points are generated by incrementing the start time by the inverse of the frequency.
    """
    time = []
    time.append(convert_unix_time(start_time))
    temp = time[0]
    for l in range(1, len_frame):
        temp = temp + datetime.timedelta(seconds=1/freq)
        time.append(temp)
    return time



def transform_empatica_data(empatica_sensor: pd.DataFrame, name: str):
    """
    Transforms Empatica sensor data into a time-indexed DataFrame.

    Parameters
    ----------
    empatica_sensor : pd.DataFrame
        DataFrame containing the raw Empatica sensor data.
    name : str
        Name to assign to the sensor data column if there is only one column.

    Returns
    -------
    pd.DataFrame
        Transformed DataFrame with time as the index and sensor data as columns.

    Notes
    -----
    - If the input DataFrame has more than one column, it is assumed to contain 'x', 'y', and 'z' acc-sensor data.
    - The first row of the DataFrame is expected to contain the Unix time.
    - The second row of the DataFrame is expected to contain the sampling frequency.
    - The function `set_time_` is used to generate the time index based on the sampling frequency and Unix time.
    """
    
    if len(empatica_sensor.columns) > 1:
        unix_time = empatica_sensor.iloc[0].values[0]
        sampling_freq = empatica_sensor.iloc[1].values[0]
        empatica_sensor = empatica_sensor[2:]    
        empatica_sensor.columns = ['x', 'y', 'z']
    else:     
        unix_time = empatica_sensor.iloc[0].values[0]
        sampling_freq = empatica_sensor.iloc[1].values[0]
        empatica_sensor = empatica_sensor[2:]  
        empatica_sensor.columns = [name]  
    
    empatica_sensor['time'] = set_time_(sampling_freq, unix_time, len(empatica_sensor))  
    empatica_sensor.set_index('time', inplace=True)  
    return empatica_sensor



def read_and_sort_data(PATH: str) -> dict:
    """
    Reads and sorts Empatica sensor data from a specified directory path.

    Parameters
    ----------
    PATH : str
        The directory path containing subfolders with sensor data files.

    Returns
    -------
    dict
        A dictionary with participant IDs as keys and their corresponding sensor data as values.

    Notes
    -----
    - The function loops through all subfolders in the specified path.
    - It reads CSV files, excluding those containing 'ibi', 'tag', or 'hr' in their filenames.
    - The function `transform_empatica_data` is used to process the sensor data.
    - The resulting sensor data is stored in a dictionary with participant IDs as keys.
    """
    all_files = []
    participants = {}
    sub_folders = os.listdir(PATH)
    for folder in range(0, len(sub_folders)):
        # Loop through all sub_folders
        path = os.path.join(PATH, sub_folders[folder])
        if os.path.isfile(path): continue
        files = glob.glob(path + "/*/*.csv")
        sensor_data = {}
        for f in files:
            if 'ibi' in f.lower() or 'tag' in f.lower() or 'hr' in f.lower(): continue
            sensor = pd.read_csv(f, header=None)
            sensor_data[str(pathlib.Path(f).name).replace('.csv', '')] = transform_empatica_data(sensor, str(pathlib.Path(f).name).replace('.csv', ''))
        participants[str(sub_folders[folder])] = sensor_data
            
        
    return participants  



