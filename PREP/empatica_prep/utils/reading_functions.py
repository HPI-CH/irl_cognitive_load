def temp_sensor_dict(participants:dict, sensor_key:str)->dict:
    """
    Extracts a specific entry from each sub-dictionary in the given dictionary.

    Parameters
    ----------
    data : dict
        The original dictionary with IDs as keys and sub-dictionaries as values.
    entry_key : str
        The key of the entry to extract from each sub-dictionary.

    Returns
    -------
    dict
        A new dictionary with the same keys as the original, but each sub-dictionary contains only the specified entry.
    """
    sensor_dict = {}
    for key, sub_dict in participants.items():
        if sensor_key in sub_dict:
            sensor_dict[key] = {sensor_key: sub_dict[sensor_key]}
    return sensor_dict


